# ------------ HELPER FUNCTIONS ---------------

def _format_date(date_str):
    """
    Converts a date string from 'YYYY,MM,DD,hh:mm' to 'DD Mon YYYY'.
    
    Example:
        format_date('2024,04,14,07:30') -> '14 Apr 2024'
    """
    if not date_str:
        return ''
    dt = datetime.strptime(date_str, "%Y,%m,%d,%H:%M")
    return dt.strftime("%d %b %Y")

def _child_url(child):
    link = child[0]["link"]
    return ARCHIVE_BASE + link if link is not None else None

def _child_sheetname(page, child):
    if page.kind == 'archive':
        return f'Fund {unescape(get_text(child[0]["text"]))}'
    elif page.kind == 'fond':
        return f'{page.parent.id} {page.id}-{unescape(get_text(child[0]["text"]))}'
    return f'sheetname-{unescape(get_text(child[0]["text"]))}'

def _child_doc_url(child):
    if len(child) < 2:
        return None
    link = child[1]["link"]
    return ARCHIVE_BASE + link if link is not None else None

_EXPR_PATTERN = re.compile(r'{[^}]+}')

def _check_string(text):
    if not text:
        return None
    if not isinstance(text, str):
        return text
    match = re.findall(_EXPR_PATTERN, text)
    if not match:
        return None
    return list(match)

def _get_cell_text(cell):
    text = cell.value
    if isinstance(text, ArrayFormula):
        text = text.text
    return text

def _check_cell(cell):
    #_logger.info(f'_check_cell[{cell.coordinate}]: {cell.value}')
    return _check_string(_get_cell_text(cell))

def _is_integer(text):
    return text is not None and text.isdigit()

_PARSE_PATTERN = re.compile(
    r'{(?P<expr>[a-zA-Z0-9_.]+)(\[(?P<index>[a-zA-Z_][a-zA-Z0-9_]*|\d+)\])?(\:(?P<modifier>[a-zA-Z_]+))?}')

def _parse_template_expr(expr):
    match = re.match(_PARSE_PATTERN, expr)
    return match.groupdict() if match else None

def _substitute(page, expr):
    try:
        fstring = '{__page__.' + expr['expr'] + '}'
        result = string.Formatter().format(fstring, __page__=page)
        if result == "None":
            result = ""
        return result
    except:
        return ""

def _copy_cell_properties(source, dest):
    # propagate border, style, font, fill, and alignment to all rows
    dest.style = source.style
    dest.border = copy(source.border)
    dest.alignment = copy(source.alignment)
    dest.font = copy(source.font)
    dest.fill = copy(source.fill)

def _process_formula(sheet, cell, first_child_row, last_child_row):
    if cell.row > first_child_row and cell.row <= last_child_row:
        # ignore table rows that are generated by progenitor table row (already handled)
        return
    text = _get_cell_text(cell)
    if isinstance(text, str) and (text[0] == '=' or text.startswith("__EQ__")):
        # formula detected
        column_range = f'{cell.column_letter}{first_child_row}:{cell.column_letter}{last_child_row}'
        if text[0] == "=":
            text = text[1:]
        elif text.startswith("__EQ__"):
            text = text[6:]
        text = text.replace("__COL__", column_range)
        text = text.replace("__FIRST__", str(first_child_row))
        text = text.replace("__LAST__", str(last_child_row))
        new_formula = f'={text}'
        #_logger.info(f'formula found: {cell.column_letter}{cell.row}: {text[1:]} --> {new_formula}')
        cell.value = new_formula
        if cell.row == first_child_row:
            # handle formula inside table
            for row in range((first_child_row+1), (last_child_row+1)):
                child_cell = sheet.cell(row=row, column=cell.column)
                _copy_cell_properties(cell, child_cell)
                child_cell.value = Translator(
                    new_formula, origin=cell.coordinate).translate_formula(child_cell.coordinate)

def _map_index(column_header_map, index):
    if index is None:
        return None

    # Convert stringified integers
    if isinstance(index, int) or _is_integer(index):
        return [int(index)]

    # Look up by name
    result = column_header_map.get(index)
    if isinstance(result, int):
        return [result]
    if isinstance(result, list):
        return result

    return None


def _set_url(cell, link_flag, url, edit_cell):
    if link_flag == "exists":
        cell.hyperlink = url
        cell.font = copy(edit_cell['linked'].font)
    elif link_flag == "linked":
        cell.hyperlink = url + "?action=edit&redlink=1"
        cell.font = copy(edit_cell['nonexistent'].font)
    else: # "unlinked" status
        cell.font = copy(edit_cell['unlinked'].font)

def _update_edit_state(entry, edit_state):
    edit_update = entry.get('edit')
    if edit_update == 'added':
        return edit_update
    if edit_update == 'changed' and edit_state != 'added':
        return edit_update
    return edit_state

def _update_link_status(entry, prev_link_status):
    cur_link_status = link_status(entry)
    if cur_link_status == 'exists':
        return cur_link_status
    if cur_link_status == 'linked' and prev_link_status != 'exists':
        return cur_link_status
    return prev_link_status

def _process_table_column(table, column_header_map, edit_cell, sheet, cell, parse, match):
    row = cell.row
    col = cell.column
    index = parse['index']
    #_logger.info(f"filling table column: {col}({index}), expr={parse['expr']}")
    mapped_index_list = _map_index(column_header_map, index)
    if index is not None or mapped_index_list is not None:
        _logger.info(f'column map: {index} -> {mapped_index_list}')
    cell_text = _get_cell_text(cell)
    for child in table["children"]:
        child_cell = sheet.cell(row=row, column=col)
        if child_cell.row != cell.row:
            # propagate border, style, font, and alignment to all rows
            _copy_cell_properties(cell, child_cell)
        if parse['expr'] == 'child':
            if mapped_index_list is not None:
                cell_value = []
                cell_hyperlink = None
                cell_edit_status = None
                for mapped_index in mapped_index_list:
                    if mapped_index < len(child):
                        table_entry = child[mapped_index]
                        cell_value.append(unescape(get_text(table_entry['text'])))
                        cell_edit_status = _update_edit_state(table_entry, cell_edit_status)
                        #_logger.info(f"cell value: {table_entry}, edit status: {cell_edit_status}")
                if cell_edit_status in edit_cell:
                    child_cell.fill = copy(edit_cell[cell_edit_status].fill)
                if parse['modifier'] == 'linked':
                    child_link_status = link_status(child[0])
                    _set_url(child_cell, child_link_status, _child_url(child), edit_cell)
                elif parse['modifier'] == 'doc_link':
                    doc_link_status = link_status(child[1]) if len(child) > 1 else "unlinked"
                    #_logger.info(f"col B: {get_text(child[0]['text'])}, {doc_link_status}, {_child_doc_url(child)}")
                    _set_url(child_cell, doc_link_status, _child_doc_url(child), edit_cell)
                child_cell.value = "; ".join(cell_value)
        elif parse['expr'] == 'empty':
            child_cell.value = ''
        elif parse['expr'] == 'col':
            contents = cell_text.replace("{col}", "")
            #_logger.info(f"col cell: {contents}")
            if row == cell.row or contents[0] != "=":
                child_cell.value = contents
            else:
                child_cell.value = Translator(
                    contents, origin=cell.coordinate).translate_formula(child_cell.coordinate)
        row += 1
    #_logger.info(f"finished table column: {col}({index})")

def _locate_first_child_row(sheet):
    for row in sheet.iter_rows():
        for cell in row:
            check = _check_cell(cell)
            if check:
                # form list of parsed template expressions for each in the cell
                parsed = [_parse_template_expr(e) for e in check]
                for parse in parsed:
                    # look for child cell expression
                    if parse['expr'] in ['empty', 'child']:
                        return cell.row
    return None

def _process_title(page, sheet):
    title = sheet.title
    check = _check_string(title)
    if check:
        for expr in check:
            parsed = _parse_template_expr(expr)
            sub = _substitute(page, parsed)
            if sub:
                title = title.replace(expr, sub)
    sheet.title = title

