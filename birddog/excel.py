_PROJECT_ROOT = Path(__file__).resolve().parents[1]
_TEMPLATE_DIR = _PROJECT_ROOT / 'resources' / 'xlsx_templates'

def list_templates():
    pattern = os.path.join(_TEMPLATE_DIR, '*.xlsx')
    return [os.path.basename(f) for f in glob.glob(pattern)]

def export_page(page, dest_file=None, template=None, table_name=None, column_map=None):
    # load template file that matches this kind of page
    _logger.info(f"export_page({page.title}: template='{template}', table_name='{table_name}', column_map='{column_map}')")
    if not template:
        template_file = f'{_TEMPLATE_DIR}/{page.kind}.xlsx'
    else:
        template_file = f'{_TEMPLATE_DIR}/{template}'
    _logger.info(f'opening template file {template_file}...')
    workbook = load_workbook(filename = template_file)
    sheet = workbook.active
    max_row = sheet.max_row
    max_col = sheet.max_column
    max_col_letter = get_column_letter(max_col)
    _logger.info(f'sheet dimensions: {max_row} rows, {max_col} cols')

    _process_title(page, sheet)

    # determine selected table for export
    if not table_name:
        table_name = page.tables[0]["name"] if page.tables else ""
    table = page.lookup_table(table_name)
    # construct column header map if needed
    column_header_map = column_map if column_map else classify_table_columns(table)

    # move rows below the table downward to make room for table rows
    num_children = len(table["children"])
    first_child_row = _locate_first_child_row(sheet)
    last_child_row = first_child_row + max(num_children, 1) - 1
    _logger.info(f"export_page: first_child_row={first_child_row}, last_child_row={last_child_row}")
    footer_range = f'A{first_child_row+1}:{max_col_letter}{max_row}'
    _logger.info(f'moving cell range: {footer_range}')
    sheet.move_range(footer_range, rows=num_children-1, cols=0, translate=False)

    # make a list of all cells with template expressions
    # (now that cells have been relocated to their final positions)
    edit_cell = {} # saves cells containing edit and formatting prototypes
    edits = [] # list of edits to be processed
    for row in sheet.iter_rows():
        for cell in row:
            check = _check_cell(cell)
            if check:
                # form list of parsed template expressions for each in the cell
                parsed = [_parse_template_expr(e) for e in check]
                for parse in parsed:
                    # check for formatting directives (before actually editing)
                    if parse['expr'] == 'edit':
                        # {edit} cells contain formatting for editing highlights
                        # save these for later use in a dict keyed on the edit modifier
                        edit_cell[parse['modifier']] = cell
                    else:
                        edits.append((cell, check, parsed))
            else:
                # check for and handle a formula
                _process_formula(sheet, cell, first_child_row, last_child_row)

    # process all the edit expressions
    for edit in edits:
        cell, matches, parses = edit
        for match, parse in zip(matches, parses):
            #_logger.info(f"processing template match: {match}, {parse}")
            if parse['expr'] in ['empty', 'child', 'col']:
                _process_table_column(
                    table, 
                    column_header_map, 
                    edit_cell, 
                    sheet, 
                    cell, 
                    parse, 
                    match)
            elif parse['expr'] == 'edit':
                # {edit} cells contain formatting for editing highlights (caught above)
                pass
            else:
                # general case: replace template expression with substitution value
                _logger.info(f"export_page template: {cell.coordinate} == {cell.value}")
                sub = _substitute(page, parse)
                if sub is not None:
                    sub = unescape(sub)
                    cell.value = cell.value.replace(match, sub)
                if parse['modifier'] == 'linked':
                    cell.hyperlink = page.url
                    cell.font = copy(edit_cell['linked'].font)
                if parse['modifier'] == 'doc_link':
                    doc_url = page.doc_url
                    if doc_url:
                        cell.hyperlink = doc_url
                        cell.font = copy(edit_cell['linked'].font)
                    if 'doc_link_edit' in page.page:
                        edit = page.page['doc_link_edit']
                        if edit in edit_cell:
                            cell.fill = copy(edit_cell[edit].fill)
                if parse['modifier'] == 'date':
                    cell.value = _format_date(cell.value)

    # all done, save and return
    if dest_file:
        _logger.info("writing export sheet to file")
        workbook.save(dest_file)
    _logger.info("finished table export")
    return workbook

class ExportManager(TaskManager):
    def __init__(self, runtime):
        self._runtime = runtime
        super().__init__("ExportManager")

    def _output_path(self, task_id):
        return f"export/{task_id}.xlsx"

    def export_page(self, title, compare=None, table_name=None, template=None, column_map=None):
        subtask = { 
            "title": title,
            "compare": compare,
            "table_name": table_name,
            "template": template,
            "column_map": column_map,
        }
        # return task_id to caller for subsequent lookup
        return self.create(title, [ subtask ])

    def is_complete(self, task_id):
        try:
            if load_cached_object(self._output_path(task_id)):
                return True
            return False
        except CacheMissError:
            return False
        except Exception as e:
            raise e

    def get_result(self, task_id):
        try:
            output = load_cached_object(self._output_path(task_id))
            if output:
                output_buffer = BytesIO()
                _logger.info(f"output size: {len(output)}")
                output_buffer.write(bytes.fromhex(output))
                output_buffer.seek(0)
                remove_cached_object(self._output_path(task_id))
                return output_buffer
            return None
        except CacheMissError:
            return None
        except Exception as e:
            raise e

    def execute_subtask(self, subtask):
        payload = subtask["payload"]
        try:
            page = self._runtime.lookup_by_title(payload["title"])
            if page:
                # avoid persisting any subsequent changes
                page = page.detached_copy()

                # put page into desired state for export
                page.prepare_to_download()
                ref_date = payload.get("compare")
                if ref_date:
                    page = page.compare(ref_date)

                # export into output memory buffer
                output_buffer = BytesIO()
                export_page(
                    page, 
                    output_buffer, 
                    payload.get("template"), 
                    payload.get("table_name"),
                    payload.get("column_map"))

                # serialize output to temp storage
                output_buffer.seek(0)
                save_cached_object(output_buffer.read().hex(), self._output_path(subtask['task_id']))

                output_buffer.seek(0)
                _logger.info(f"{subtask['task_id']}: export task finished. output length: {len(output_buffer.read())}")
        except Exception as err:
            _logger.info(f"Exception in export task: {err}")

    def complete_task(self, task_desc, subtasks):
        _logger.info(f"{task_desc['task_id']}: completed")

